# Arithmatic operators
# +, -, *, /, %, ** (exponentiation)
#/ // (floor division)

a = 23
b = 45

print(b//a)

# exponentiation
print(2**5)
print(100 ** 0.5)

# remainder
print(24%5)

#comparison operators
# ==, !=, >, <, >=, <=

print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)

#logical operators
# and or not
# in and both condition have to be true 
# in or one condition have to be true
# in not if true that will become false or viceversa
print(a > 10 and b < 50)
print(a > 10  and b > 50)
print(a > 10 or b < 50)
print(not(a > 10 and b < 50))  

